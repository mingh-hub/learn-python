# 字符串

## 字符串定义

### 1. 双引号定义（推荐）
str1 = "Hello Python"
print(str1)

### 2. 单引号定义
str2 = 'Hello Python'
print(str2)

### 3. 三引号定义（可换行）
str3 = """
起来！不愿做奴隶的人们
！！！！
"""
print(str3)

## 字符串拼接

### + 号拼接（无法拼接字符串与非字符串）
str_connect1 = "你好：" + "Java"
print(str_connect1)

### 多个字符串字面量可以直接写
str_connect2 = "你好：" "Python"
print(str_connect2)

