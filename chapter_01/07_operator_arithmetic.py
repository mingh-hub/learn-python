# 精度损失：计算机底层是基于二进制进行数据的存储和处理，二进制无法准确的表示所有的小数
# print(f"x - y = {x - y}")

reflect_on = """
计算机中的 float 通常遵循 IEEE 754 双精度浮点数标准，使用二进制存储小数。

0.5 可以精确表示：十进制 0.5 等于二进制 0.1，是有限位二进制小数。
0.4 无法精确表示：十进制 0.4 转换成二进制是 0.0110011001100110...（1100 无限循环），只能在有限的 53 位尾数（双精度）处截断，产生舍入误差。
当 0.5 减去一个略大于 0.4 的近似值时，结果就变成了一个略小于 0.1 的数，显示为 0.09999999999999998

如何解决？
1. 需要精确小数（如金融计算） → 使用 Decimal
from decimal import Decimal
x = Decimal('0.5')
y = Decimal('0.4')
print(x - y)   # 0.1

2. 浮点数比较 → 使用容差 math.isclose
import math
x, y = 0.5, 0.4
# 不要用 == 判断，而用近似比较
print(math.isclose(x - y, 0.1))   # True

3. 显示时控制小数位数 → 使用 round 或格式化
print(round(x - y, 2))      # 0.1
print(f"{x - y:.1f}")       # 0.1
"""
print(reflect_on)
