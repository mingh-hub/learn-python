# 列表常用方法-reverse

"""
1. 方法签名与基本用法
    list.reverse()
1.1 参数：无。
1.2 None。该方法直接修改原列表，将列表中的元素顺序完全颠倒。
"""

fruits = ['apple', 'banana', 'cherry']
fruits.reverse()
print(fruits)   # ['cherry', 'banana', 'apple']

"""
2. 返回值 —— 最常见的陷阱
    reverse() 返回 None
"""

"""
3. 时间复杂度：O(n)
    list.reverse() 的时间复杂度为 O(n)，其中 n 是列表长度。
3.1 原因：它需要将首尾元素逐一交换。它会遍历前一半元素，将其与对称位置的后一半元素交换，总共执行约 n/2 次交换操作，因此与列表长度成正比。
3.2 无论列表元素是什么类型，交换操作本身是常数时间，所以整体为 O(n)。
"""

"""
4. 与 reversed() 和切片 [::-1] 的对比
    这是 Python 中三种最常用的反转列表的方式，各自特点鲜明：
                                            reverse()                                   reversed()                                  切片 [::-1]
    方法                                 list.reverse()                              reversed(seq)                            list[::-1]
    是否修改原列表                是                                              否                                              否
    返回类型                          None                                         迭代器                                       新列表
    返回内容                          无                                              反向迭代器                                 反转后的列表
    时间复杂度                      O(n)                                           O(1)                                          O(n)
    内存开销                         O(1)（原地交换）                       O(1)（惰性求值）                      O(n)（分配新列表）
"""
print("=================与 reversed() 和切片 [::-1] 的对比：使用 reversed() 内置函数=================")
# 4.1 使用 reversed() 内置函数
# reversed() 返回一个反向迭代器，原序列完全不变。它适用于任何序列类型（列表、元组、字符串等）。
a = [1, 2, 3]
rev_iter = reversed(a)
print(list(rev_iter))   # [3, 2, 1]
print(a)                    # [1, 2, 3]  原列表不变

# 如果只需要在循环中反向遍历，reversed() 是最高效的方式，因为它不复制列表（反向迭代器），惰性生成元素。
for item in reversed(a):
    print(item)

print("=================与 reversed() 和切片 [::-1] 的对比：使用切片 [::-1]=================")
# 4.2 使用切片 [::-1]
# 切片 list[::-1] 会创建原列表的一份浅拷贝，并返回反转后的新列表。原列表保持不变。
# 如果需要新的反转列表且不想改变原数据，可以用切片；但如果只想迭代，则更推荐 reversed() 以避免不必要的内存分配。
a = [1, 2, 3]
b = a[::-1]     # b = [3, 2, 1], a = [1, 2, 3]
print(b)

# 4.3 如何选择？
# 需要原地反转，节省内存 → list.reverse()
# 想保留原列表，获得新列表 → 切片 [::-1] 或 list(reversed(seq))
# 只是反向遍历，不构建新列表 → reversed() 迭代器
# 对字符串、元组等不可变序列反转 → reversed() 结合 ''.join() 或切片 [::-1]（返回对应类型的新对象）

"""
5. 注意事项与易错点
5.1 返回值是 None
5.2 浅拷贝与嵌套列表
5.3 不可变序列没有 reverse() 方法
"""
print("=================注意事项与易错点：浅拷贝与嵌套列表=================")
# reverse() 只反转元素引用的顺序，不复制嵌套对象本身。如果列表包含可变子对象（如列表、字典），反转后这些子对象还是原来的引用，修改它们会影响所有引用处。
nested = [[1, 2], [3, 4]]
nested.reverse()
print(nested)          # [[3, 4], [1, 2]]
nested[0].append(99)
print(nested)          # [[3, 4, 99], [1, 2]]  原始子列表被改变
# 如果需要一个全新的、深度拷贝的反转列表，应使用：
import copy
new_list = copy.deepcopy(nested)[::-1]
nested[0].append(100)
print(new_list)

print("=================注意事项与易错点：不可变序列没有 reverse() 方法=================")
# 元组、字符串等是不可变序列，它们没有 reverse() 方法。要反转它们，必须用 reversed() 或切片创建新对象。
t = (1, 2, 3)
# t.reverse()   # AttributeError: 'tuple' object has no attribute 'reverse'
rev_tuple = tuple(reversed(t))   # 或者 t[::-1]
print(rev_tuple)

"""
6. 内部原理简述

list.reverse() 在 CPython 底层实现非常直观：
1. 获取列表长度 n。
2. 使用两个指针（或索引），一个从头部 0 开始，一个从尾部 n-1 开始。
3. 交换这两个位置的元素引用。
4. 头指针向后移动，尾指针向前移动，直到两者相遇或交错。
5. 整个过程只交换对元素的引用（PyObject 指针），而不移动或复制元素本身的数据，所以空间复杂度为 O(1)。
6. 实现是 C 语言层面完成的，非常高效。
"""

"""
7. 性能优化建议

7.1 原地反转优先使用 list.reverse()，时间和空间效率都是最优的。
7.2 当只需反向迭代时，绝对不要先 reverse() 再正向遍历（这样会修改列表且增加 O(n) 的时间），直接用 for x in reversed(my_list):。
7.3 对于需要新列表的场景，如果对内存不敏感，使用 new = old[::-1] 简洁清晰；如果追求极致性能且想复用旧列表，可以先 reverse() 再用完后 reverse() 回来（但需注意代码可读性和线程安全性）。
7.4 在多线程环境中操作共享列表，reverse() 不是原子操作，需要加锁。
"""
