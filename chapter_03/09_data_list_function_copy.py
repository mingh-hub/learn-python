# 列表常用方法-copy

"""
1. 方法签名与基本用法
    list.copy()
1.1 参数：无。
1.2 返回值：返回一个新的列表对象，包含与原列表相同元素的相同引用（浅拷贝）。

"""
print("=================方法签名与基本用法=================")
original = [1, 2, 3]
new_list = original.copy()
print(new_list)   # [1, 2, 3]
print(original)   # [1, 2, 3]  原列表不变
print(original is new_list)  # False  不同对象

"""
2. 简单介绍 浅拷贝（Shallow Copy） 与 深拷贝（Deep Copy）

浅拷贝（Shallow Copy）
1. 创建一个新的复合对象（如列表、字典、自定义对象等）。
2. 新对象内部存储的元素引用，与原对象中对应元素的引用完全相同。
3. 也就是说，浅拷贝只复制容器本身，不会递归复制元素本身。
    3.1 如果元素是可变类型（如列表、字典、自定义对象），修改这些子对象的内部状态会同时反映到原列表和新列表中，因为它们共享同一个子对象。
    3.2 如果元素是不可变类型（整数、字符串、元组等），修改“拷贝”中的元素不影响原列表，因为修改不可变对象实际上是替换引用。
4. 实现方式
    4.1 列表：list.copy()、list[:]、list() 构造函数、copy.copy()
    4.2 字典：dict.copy()、copy.copy()
    4.3 集合：set.copy()、copy.copy()

深拷贝（Deep Copy）
1. 创建一个新的复合对象。
2. 递归地复制原对象内部所有子对象，直到所有嵌套层次完全独立。
3. 最终生成一个与原对象内容完全相同、但完全独立的全新对象，修改任何层次都不会影响原对象。
4. 实现方式
    new_obj = copy.deepcopy(original_obj)
"""
print("=================浅拷贝（Shallow Copy）=================")
# original 包含可变子元素的列表
original = [[1, 2], [3, 4]]
shallow = original.copy()

shallow[0].append(99)     # 修改嵌套的子列表，引用没变
print(shallow)   # [[1, 2, 99], [3, 4]]
print(original)  # [[1, 2, 99], [3, 4]]  <-- 原列表也被改变了！

shallow[0] = [1, 2, 99]       # 替换整个元素（改变引用）
shallow[0].append(199)
print(shallow)   # [[1, 2, 99, 199], [3, 4]]
print(original)  # [[1, 2, 99], [3, 4]]  <-- 原列表不受影响

"""
3. 常见使用场景
3.1 保留原列表的快照
3.2 在循环中修改列表时避免迭代问题
3.3 避免函数内部修改影响到外部
"""

print("=================常见使用场景：保留原列表的快照=================")
data = [10, 20, 30]
data_backup = data.copy()
data.append(40) # 新增引用，原列表不变
print(data_backup)   # [10, 20, 30]  不受影响

print("=================常见使用场景：在循环中修改列表时避免迭代问题=================")
numbers = [1, 2, 3, 2, 4]
for num in numbers.copy():
    if num == 2:
        numbers.remove(num)
print(numbers)   # [1, 3, 4]

print("=================常见使用场景：避免函数内部修改影响到外部=================")
def process(items):
    items = items.copy()   # 局部副本
    items.append('done')
    return items

my_list = [1, 2]
result = process(my_list)
print(result)   # [1, 2, 'done']
print(my_list)   # [1, 2]  未受影响

"""
4. 注意事项与易错点
4.1 浅拷贝与嵌套可变对象
    如前所述，这是最容易出错的地方。如果你修改了嵌套子对象，原列表也会变化。
4.2 对不可变对象无需深拷贝 *****
    如果列表只包含数字、字符串、元组等不可变类型，浅拷贝已完全独立，无需 deepcopy 带来额外性能开销。
4.3 空列表拷贝是安全的
    empty = []
    new_empty = empty.copy()   # 返回新空列表，两者独立
4.4 copy() 是列表方法，仅适用于列表
    元组、字符串没有 copy() 方法。需要拷贝时可使用 [:] 或 copy.copy()。
"""

"""
5. 内部原理简述
    list.copy() 在 CPython 中直接调用底层 C 函数 list_copy_impl（或类似实现），大致过程如下：
5.1 计算原列表的长度 n。
5.2 申请一块新的内存，创建长度为 n 的列表对象。
5.3 遍历原列表的底层指针数组，将每个元素指针（PyObject *）复制到新列表的相应位置。
5.4 增加这些元素对象的引用计数（因为新列表也引用了它们）。
5.5 返回新列表对象。
    因为仅仅复制指针而不创建元素的新对象，所以是浅拷贝。整个过程是 O(n)，但常数很小，速度很快。
"""

"""
6. 性能提示
6.1 对于大多数场景，list.copy() 和切片 [:] 性能几乎一致。在 Python 3.11+ 中，某些基准测试显示 copy() 可能略微快一点，但差异可以忽略不计。
6.2 如果需要一个独立的一维列表，浅拷贝就足够了，不要滥用 deepcopy——它会递归遍历所有对象，非常慢且消耗大量内存。
6.3 如果你只需要读取列表而不修改，考虑直接引用，或者用不可变序列（如元组）避免意外拷贝。
"""
