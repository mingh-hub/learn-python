# 数据容器：字符串（str）

"""
1. 创建字符串
    可以用单引号、双引号或三引号创建，三引号常用于多行文本或文档字符串。
"""
s1 = 'hello'
s2 = "world"
s3 = '''这是
多行
字符串'''
s4 = """也可以
这样写"""

"""
2. 不可变性
    字符串一旦创建，不能修改其中的字符。任何“修改”操作都会返回一个新的字符串。
"""
s = "hello"
# s[0] = "H"    # 会报错 TypeError
new_s = "H" + s[1:]   # "Hello"，实际上是创建了新字符串
print(new_s)

"""
3. 索引与切片
    字符串是序列，支持用下标访问单个字符（索引从 0 开始），以及切片获取子串。
    切片语法[start:end:step]
        start：开始索引，默认为 0
        end：结束索引，默认字符串长度
        step：结束索引，默认为1，-1表示从后向前
"""
s = "Python"
s[0]      # 'P'       第一个字符
s[-1]     # 'n'       最后一个字符
s[1:4]    # 'yth'     索引 1 到 3
s[:3]     # 'Pyt'     前三个
s[3:]     # 'hon'     从第四个到最后
s[::2]    # 'Pto'     每隔一个字符
s[::-1]   # 'nohtyP'  反转字符串
