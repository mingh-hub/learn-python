# 字符串常用方法-join

"""
1. 方法签名
    str.join(iterable)
        str — 连接符
        iterable — 由字符串组成的可迭代对象
"""

"""
2. 基本用法
    使用指定连接符，将多个字符串拼接成一个新字符串。
"""
print("=================基本用法=================")
words = ["hello", "python", "world"]
print(" ".join(words)) # hello python world

"""
3. 使用不同连接符
"""
print("=================使用不同连接符=================")
items = ["2026", "06", "14"]
print("-".join(items)) # 2026-06-14
print("/".join(items)) # 2026/06/14
print("".join(items))  # 20260614

"""
4. join() 要求元素都是字符串
    如果列表中有数字，需要先转换为字符串。
"""
print("=================join() 要求元素都是字符串=================")
nums = [1, 2, 3]
print(",".join(str(num) for num in nums)) # 1,2,3

"""
5. 与 + 拼接的区别
    多个字符串批量拼接时，join() 通常更清晰，也更适合处理列表。
"""
print("=================与 + 拼接的区别=================")
letters = ["P", "y", "t", "h", "o", "n"]
print("".join(letters)) # Python

"""
6. 常见应用场景
6.1 拼接路径片段
6.2 拼接 CSV 风格文本
6.3 将列表转换为展示文本
"""
print("=================常见应用场景：拼接 CSV 风格文本=================")
row = ["Alice", "25", "Shanghai"]
print(",".join(row))

"""
7. 注意事项汇总
- join() 是连接符字符串的方法，不是列表的方法。
- iterable 中的元素必须都是字符串。
- 空列表 join 的结果是空字符串 ""。
- 批量拼接字符串时，优先考虑 join()。
"""
